export function PriceDisplayVariant1(props = {}) {
  const state = {
    name: 'PriceDisplay',
    variant: 1,
    props: props,
    visible: props.visible !== false,
    className: props.className || 'nm-pricedisplay-1',
    disabled: !!props.disabled,
    loading: !!props.loading
  };
  function renderLabel() {
    if (props.label) return String(props.label);
    if (props.title) return String(props.title);
    return 'PriceDisplay ' + 1;
  }
  function renderValue() {
    if (props.value == null) return '';
    if (typeof props.value === 'number') return props.value.toLocaleString('en-IN');
    return String(props.value);
  }
  function shouldShow() {
    if (state.loading) return false;
    if (props.hideEmpty && !props.value && !props.children) return false;
    return state.visible;
  }
  function getAriaLabel() {
    return props.ariaLabel || renderLabel();
  }
  return {
    ...state,
    label: renderLabel(),
    value: renderValue(),
    show: shouldShow(),
    ariaLabel: getAriaLabel(),
    testId: 'nm-pricedisplay-v1'
  };
}

